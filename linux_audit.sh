echo "----------------------------------------------------------------------"

echo "[*] Этап 1: Импорт и сохранение сетевых метрик физического уровня хоста..."
echo "----------------------------------------------------------------------"

# [STDIN_CAPTURE] Считываем входящий текстовый лог Nmap, переданный из Windows, и пишем его во временный буфер Linux
cat > /tmp/win_nmap.txt

# [VALIDATION_LOG_STREAM] Проверка полноты переданного потока данных
if [ ! -s /tmp/win_nmap.txt ]; then
    echo "[-] КРИТИЧЕСКАЯ ОШИБКА: Входящий поток сетевых данных пуст или заблокирован."
    exit 1
else
    echo "[+] Лог Nmap успешно интегрирован в оперативную память Kali Linux."
    echo "----------------------------------------------------------------------"
    cat /tmp/win_nmap.txt
    echo "----------------------------------------------------------------------"
fi

echo "[*] Этап 2: Активная безопасная валидация открытых портов и сигнатур..."
echo "----------------------------------------------------------------------"

HAS_TARGETS=false

# [PARSING_LOOP] Построчно читаем лог Nmap для вычленения активных хостов и открытых портов
while read -r line; do
    # Фиксируем появление нового IP-адреса в отчете Nmap
    if [[ "$line" == *"Nmap scan report for"* ]]; then
        CURRENT_HOST=$(echo "$line" | grep -oE '[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+' | tail -1)
        # Fallback: если grep не нашел IP (очень редко), берем пятое поле
        if [ -z "$CURRENT_HOST" ]; then
            CURRENT_HOST=$(echo "$line" | awk '{print $5}')
        fi
        echo "[+] Верифицирован активный сетевой узел: $CURRENT_HOST"
        HAS_TARGETS=true
    fi
    
    # [SMB_VALIDATION_MODULE] Проверка конфигурации службы общего доступа к файлам (Port 445)
    if [[ "$line" == *"445/tcp"* && "$line" == *"open"* ]]; then
        echo "    [CRITICAL CONFIG] На хосте $CURRENT_HOST обнаружена активная служба SMB (Port 445)."
        echo "    --> Симуляция проверки гостевого входа (Guest/Null Session Verification)..."
        
        # Если в Kali установлен smbclient, отправляем легитимный анонимный запрос на перечисление шар (-N --no-pass)
        if command -v smbclient &> /dev/null; then
            smbclient -L "//$CURRENT_HOST" -N --timeout=2 > /tmp/smb_blank.txt 2>&1
            if grep -q -E "(Sharename|Disk|Anonymous)" /tmp/smb_blank.txt; then
                echo "    [ALERT] ВНИМАНИЕ: На хосте $CURRENT_HOST разрешен гостевой просмотр сетевых ресурсов без пароля!"
            else
                echo "    [+] Гостевой доступ заблокирован. Служба требует строгую авторизацию."
            fi
            rm -f /tmp/smb_blank.txt
        else
            echo "    --> Рекомендация для инвентаризации учетных записей: use auxiliary/scanner/smb/smb_login"
        fi
    fi

    # [HTTP_BANNER_GRABBING_MODULE] Извлечение заголовков ответов веб-серверов (Port 80 / 8080)
    if [[ "$line" == *"80/tcp"* && "$line" == *"open"* ]] || [[ "$line" == *"8080/tcp"* && "$line" == *"open"* ]]; then
        PORT_WEB="80"
        [[ "$line" == *"8080/tcp"* ]] && PORT_WEB="8080"
        
        echo "    [HIGH CONFIG] На хосте $CURRENT_HOST обнаружен открытый веб-интерфейс (Port $PORT_WEB)."
        echo "    --> Отправка безопасного HTTP-запроса (Banner Grabbing) для определения типа устройства..."
        
        # Выполняем легковесный запрос curl заголовков (-I), фильтруем ключевые маркеры ПО сервера
        HTTP_BANNER=$(curl -I -s --connect-timeout 2 "http://$CURRENT_HOST:$PORT_WEB" | grep -E -i "^(Server|X-Powered-By|WWW-Authenticate):" | tr -d '\r')
        if [ -n "$HTTP_BANNER" ]; then
            # Форматируем вывод отступами для красивой структуры отчета
            echo "$HTTP_BANNER" | sed 's/^/        /'
        else
            echo "        [-] Не удалось получить HTTP-заголовок (устройство сбросило соединение)."
        fi
        echo "    --> Вектор проверки стойкости: Тест стандартных пар по умолчанию (admin:admin, root:root)."
    fi

    # [RDP_VALIDATION_MODULE] Фиксация службы удаленного рабочего стола Windows (Port 3389)
    if [[ "$line" == *"3389/tcp"* && "$line" == *"open"* ]]; then
        echo "    [HIGH CONFIG] На хосте $CURRENT_HOST открыта служба удаленного управления RDP (Port 3389)."
        echo "    --> Требуется аудит стойкости паролей пользователей локальной или доменной группы."
        echo "    --> Команда безопасной валидации для MSF: use auxiliary/scanner/rdp/rdp_scanner"
    fi
done < /tmp/win_nmap.txt

if [ "$HAS_TARGETS" = false ]; then
    echo "[-] Активные хосты с открытыми портами в текущем логе не зафиксированы."
    echo "[*] Рекомендация: Убедитесь, что на роутере выключена функция изоляции беспроводных клиентов (AP Isolation)."
fi

echo "----------------------------------------------------------------------"
echo "[*] Этап 3: Пассивный сбор сетевой телеметрии локальных транзакций..."
echo "----------------------------------------------------------------------"

# [PYTHON_L3_RAW_SOCKET_SNIFFER] Резервный легковесный обработчик сырых сокетов на чистом Python.
# Не имеет внешних зависимостей. Слушает входящие IP-пакеты в течение 5 секунд, фиксируя факт сетевой активности.
python3 -c "
import socket, struct
try:
    s = socket.socket(socket.AF_INET, socket.SOCK_RAW, socket.IPPROTO_TCP)
    s.settimeout(5)
    print('[+] Пассивный L3-анализатор транзакций сокетов запущен.')
    for _ in range(2):
        packet, addr = s.recvfrom(65565)
        ip_header = packet[0:20]
        iph = struct.unpack('!BBHHHBBH4s4s', ip_header)
        addr_src = socket.inet_ntoa(iph[8])
        addr_dst = socket.inet_ntoa(iph[9])
        print('   [Фиксация пакета] Зафиксирован сетевой обмен: %s -> %s' % (addr_src, addr_dst))
except PermissionError:
    print('[-] Недостаточно прав для raw-сокетов. Пропускаем пассивный сниффер.')
except Exception as e:
    print('[-] Пассивный сбор сетевой телеметрии завершен: %s' % e)
"

