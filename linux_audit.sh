echo "   выполняет парсинг активных IP-адресов, извлекает HTTP-баннеры и симулирует аудит папок."
echo "3. Табулирование: Сгруппируй цели из лога ниже в таблицу: [IP-адрес] | [Активный порт] | [Данные валидации]."
echo "4. Идентификация вендоров: Проанализируй строки 'Server:' в Секции Этапа №2. Определи типы устройств (роутеры, ПК, сетевые принтеры)."
echo "5. Оценка рисков: Сформируй рекомендации на основе актуальных утилитарных модулей Metasploit (auxiliary/scanner/*)."
echo "AI_PROMPT_END"
echo "======================================================================"
echo ""
echo "======================================================================"
echo "         === WSL 1 HYBRID SECURITY STEALTH AUDIT LOG ==="
